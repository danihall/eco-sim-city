CREATE TABLE IF NOT EXISTS mutable.employments (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INT NOT NULL REFERENCES mutable.cities(id) ON DELETE CASCADE,
    worker_artifact_id SMALLINT NOT NULL REFERENCES static.artifacts(id),
    employer_anchor_q SMALLINT NOT NULL CHECK (employer_anchor_q >= 0 AND employer_anchor_q <= 127),
    employer_anchor_r SMALLINT NOT NULL CHECK (employer_anchor_r >= 0 AND employer_anchor_r <= 127),
    workers_anchor_q SMALLINT NOT NULL CHECK (workers_anchor_q >= 0 AND workers_anchor_q <= 127),
    workers_anchor_r SMALLINT NOT NULL CHECK (workers_anchor_r >= 0 AND workers_anchor_r <= 127),
    jobs_count SMALLINT NOT NULL CHECK (jobs_count > 0),

    UNIQUE (city_id, employer_anchor_q, employer_anchor_r, workers_anchor_q, workers_anchor_r)
);

CREATE INDEX IF NOT EXISTS index_employments_worker_anchor
    ON mutable.employments (city_id, workers_anchor_q, workers_anchor_r);
CREATE INDEX IF NOT EXISTS index_employments_employer_anchor
    ON mutable.employments (city_id, employer_anchor_q, employer_anchor_r);

