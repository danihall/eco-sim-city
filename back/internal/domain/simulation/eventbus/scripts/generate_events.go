//go:build ignore

package main

import (
	"bytes"
	"cmp"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"iter"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"
)

type Event struct {
	Name           string
	Prefix         string
	DataStructname string
}

type generatorEvents struct {
	Events []Event
}

const events_template = `// Code generated by scripts/generate_events. DO NOT EDIT.
package eventbus

const (
{{- range $index, $item := .Events}}
    {{- if eq $index 0 }}
    {{ $item.Name }} EventType = iota
    {{- else }}
    {{ $item.Name }}
    {{- end}}
{{- end}}
)

const events_count = {{len .Events}}
{{- range .Events}}

func ({{ .Prefix }} {{ .DataStructname }}) Type() EventType {
	return {{ .Name }}
}
{{- end}}
`

func main() {
	current_folder, err := os.Getwd()
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}
	entries, err := os.ReadDir(current_folder)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	generator_data := generatorEvents{
		Events: []Event{},
	}

	reg := regexp.MustCompile("^.|_.")

	for event, node := range effectiveEventNames(entries, current_folder) {
		event_name := reg.ReplaceAllStringFunc(event, func(match string) string {
			return strings.ToUpper(string(match[len(match)-1]))
		})

		expected_struct_name := event_name + "Data"
		data_struct_name, ok := findEventStructName(node, expected_struct_name)
		if !ok {
			slog.Error(
				"damn! expected_struct_name not found",
				"expected_struct_name", expected_struct_name,
			)
			os.Exit(1)
		}

		generator_data.Events = append(generator_data.Events, Event{
			Name:           event_name,
			Prefix:         string(event[0]),
			DataStructname: data_struct_name,
		})
	}

	slices.SortFunc(generator_data.Events, func(a, b Event) int {
		return cmp.Compare(a.Name, b.Name)
	})

	tmpl := template.Must(template.New("events").Parse(events_template))

	var buffer bytes.Buffer
	err = tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	formatted_code, err := format.Source(buffer.Bytes())
	if err != nil {
		slog.Error("damn!", "cannot format code", err)
		os.Exit(1)
	}

	generated_file_path := "./events_generated.go"

	file, err := os.Create(generated_file_path)
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, string(formatted_code))
	slog.Info(generated_file_path + " generated with success!")
}

func effectiveEventNames(
	entries []os.DirEntry,
	current_folder string,
) iter.Seq2[string, *ast.File] {
	return func(yield func(event_name string, node *ast.File) bool) {
		for index := range entries {
			entry := entries[index]

			if entry.IsDir() {
				continue
			}

			file_name := entry.Name()
			file_ext := filepath.Ext(file_name)

			if file_ext != ".go" {
				continue
			}

			file_name, ok := strings.CutSuffix(file_name, file_ext)

			if strings.EqualFold(file_name, "eventbus") ||
				strings.EqualFold(file_name, "events_generated") {
				continue
			}

			event_name, ok := strings.CutPrefix(file_name, "event_")
			if !ok {
				continue
			}

			fset := token.NewFileSet()
			node, err := parser.ParseFile(fset, current_folder+"/"+entry.Name(), nil, 0)
			if err != nil {
				slog.Error("damn!", "cannot parse file", err)
				os.Exit(1)
			}

			if !yield(event_name, node) {
				return
			}
		}
	}
}

func findEventStructName(node *ast.File, expected_struct_name string) (string, bool) {
	var found_name string

	ast.Inspect(node, func(n ast.Node) bool {
		decl, ok := n.(*ast.GenDecl)
		if !ok || decl.Tok != token.TYPE {
			return true
		}

		for _, spec := range decl.Specs {
			type_spec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}

			_, ok = type_spec.Type.(*ast.StructType)
			if !ok {
				continue
			}

			if type_spec.Name.Name == expected_struct_name {
				found_name = type_spec.Name.Name
				return false
			}
		}
		return true
	})

	return found_name, len(found_name) > 0
}
