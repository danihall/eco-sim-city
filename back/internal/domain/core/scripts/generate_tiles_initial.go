package main

import (
	"bytes"
	"fmt"
	"log/slog"
	"os"
	"slices"
	"text/template"

	"git.sr.ht/~danihall/foss-eco-simcity-hex-back/internal/domain/core"
	"git.sr.ht/~danihall/foss-eco-simcity-hex-back/internal/domain/core/data"
)

type generatorTile struct {
	KindType     core.KindType
	ArtifactType core.ArtifactType
	Label        string
	Q            uint8
	R            uint8
	Ghg1         int16
	LandValue    int16
}

const initial_tiles_template = `// Code generated by scripts/generate_initial_tiles. DO NOT EDIT.
package data

import "git.sr.ht/~danihall/foss-eco-simcity-hex-back/internal/domain/core"

var InitialTiles = [core.TilesCount]core.Tile{
{{- range .}}
	{
		SuperKind: core.Natural, Kind: core.{{.KindType.String}},
		Artifact: core.ArtifactInstance{
			Name: core.{{.ArtifactType.String}}, Label: "{{.Label}}", Status: core.Step_3_DeliveredOperational,
		},
		Position: core.TilePosition{Q: {{.Q}}, R: {{.R}}}, Anchor: core.TilePosition{Q: {{.Q}}, R: {{.R}}},
		Stats: core.TileSpatialStats{
			Pollution: core.Pollution{Ghg1: {{.Ghg1}}},
			Desirability: core.Desirability{LandValue: {{.LandValue}}},
		},
	},
{{- end}}
}
`

func main() {
	err := checkBaseTiles()
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	all_super_kinds := []core.SuperKind{
		data.SeedSuperKindNatural,
		data.SeedSuperKindPublicSystems,
		data.SeedSuperKindIndustrial,
		data.SeedSuperKindResidential,
	}

	temp_registry_artifacts := make(map[core.ArtifactType]core.Artifact)
	for _, super_kind := range all_super_kinds {
		for _, kind := range super_kind.Kinds {
			for _, artifact := range kind.Artifacts {
				artifact.Effects.Spatial = _mergeWithSpatialKindEffects(
					artifact.Effects.Spatial,
					kind.Effects.Spatial,
				)
				temp_registry_artifacts[artifact.Name] = artifact
			}
		}
	}

	var generator_data [core.TilesCount]generatorTile

	for index := range data.BaseTiles {
		tile := &data.BaseTiles[index]
		artifact := temp_registry_artifacts[tile.Artifact.Name]

		generator_data[index] = generatorTile{
			KindType:     tile.Kind,
			ArtifactType: tile.Artifact.Name,
			Label:        artifact.Labels[0],
			Q:            tile.Position.Q,
			R:            tile.Position.R,
			Ghg1:         artifact.SpatialEffect(core.Ghg1),
			LandValue:    artifact.SpatialEffect(core.LandValue),
		}
	}

	tmpl := template.Must(template.New("initial_tiles").Parse(initial_tiles_template))

	var buffer bytes.Buffer
	err = tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	file, err := os.Create("./tiles_initial_generated.go")
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, buffer.String())
	slog.Info("tiles_initial_generated.go generated with success!")
}

func checkBaseTiles() error {
	if len(data.BaseTiles) != int(core.TilesCount) {
		return fmt.Errorf(
			"wrong number of tiles! expected: %d, received: %d",
			core.TilesCount,
			len(data.BaseTiles),
		)
	}

	const start_q = 0
	const start_r = 0
	row_index := 0

	for chunk := range slices.Chunk(data.BaseTiles, 128) {
		column_index := 0

		for index := range chunk {
			tile := chunk[index]
			if int(tile.Position.Q) != start_q+column_index ||
				int(tile.Position.R) != start_r+row_index {
				return fmt.Errorf(
					"raw tiles coordinates are not continuous!"+
						"in row %d at column %d. Expected Q=%d got %d. Expected R=%d got %d",
					row_index,
					column_index,
					start_q+column_index,
					tile.Position.Q,
					start_r+row_index,
					tile.Position.R,
				)
			}
			column_index++
		}
		row_index++
	}

	return nil
}

// NOTE copy-pasted from registry.go
func _mergeWithSpatialKindEffects(
	artifact_effects_spatial []core.SpatialEffect,
	kind_effects_spatial []core.SpatialEffect,
) []core.SpatialEffect {
	merged := make([]core.SpatialEffect, 0, len(artifact_effects_spatial)+len(kind_effects_spatial))
	merged = append(merged, artifact_effects_spatial...)

	for index := range kind_effects_spatial {
		exists := slices.ContainsFunc(artifact_effects_spatial, func(item core.SpatialEffect) bool {
			return kind_effects_spatial[index].Type == item.Type
		})

		if !exists {
			merged = append(merged, kind_effects_spatial[index])
		}
	}

	return merged
}
