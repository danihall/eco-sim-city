//go:build ignore

package main

import (
	"bytes"
	"cmp"
	"fmt"
	"log/slog"
	"os"
	"slices"
	"text/template"

	"git.sr.ht/~danihall/foss-eco-simcity-hex-back/internal/domain/core"
	"git.sr.ht/~danihall/foss-eco-simcity-hex-back/internal/domain/core/data"
)

//FIXME rename "artifacts_display_props" "artifact_sizes"

type generatorArtifactsDisplayProps struct {
	Artifacts []core.Artifact
}

const artifacts_sizes_template = `// Code generated by scripts/generate_artifacts_sizes. DO NOT EDIT.
const ARTIFACTS_SIZES = {
{{- range .Artifacts}}
	"{{.Name}}": {
		hex_width: {{.Width}},
		hex_height: {{.Height}},
	},
{{- end}}
} as const;

type ArtifactSizeId = keyof typeof ARTIFACTS_SIZES;

export type { ArtifactSizeId };
export { ARTIFACTS_SIZES };
`

func main() {
	all_super_kinds := []core.SuperKind{
		data.SeedSuperKindNatural,
		data.SeedSuperKindPublicSystems,
		data.SeedSuperKindIndustrial,
		data.SeedSuperKindResidential,
	}

	generator_data := generatorArtifactsDisplayProps{
		Artifacts: []core.Artifact{},
	}

	for _, super_kind := range all_super_kinds {
		for _, kind := range super_kind.Kinds {
			for _, artifact := range kind.Artifacts {
				generator_data.Artifacts = append(generator_data.Artifacts, artifact)
			}
		}
	}

	slices.SortFunc(generator_data.Artifacts, func(a, b core.Artifact) int {
		return cmp.Compare(a.Name, b.Name)
	})

	tmpl := template.Must(template.New("artifacts").Parse(artifacts_sizes_template))

	var buffer bytes.Buffer
	err := tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	generated_file_path := "../../../shared/artifacts_size.ts"

	file, err := os.Create(generated_file_path)
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, buffer.String())
	slog.Info(generated_file_path + " generated with success!")
}
