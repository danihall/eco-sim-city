//go:build ignore

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log/slog"
	"os"
	"strings"
	"text/template"
)

type generatorMapping struct {
	MapName string
	Prefix  string
	Items   []struct {
		Name string
		ID   uint8
	}
}

const mapping_template = `// Code generated by scripts/generate_mappings. DO NOT EDIT.
const {{.MapName}}_BY_ID = {
{{- range .Items}}
	{{.ID}}: "{{.Name}}",
{{- end}}
} as const;

const {{.MapName}}_BY_NAME = {
{{- range .Items}}
	"{{.Name}}": {{.ID}},
{{- end}}
} as const;

type {{.Prefix}}Id = keyof typeof {{.MapName}}_BY_ID;
type {{.Prefix}}Name = keyof typeof {{.MapName}}_BY_NAME;

export type { {{.Prefix}}Id, {{.Prefix}}Name };
export { {{.MapName}}_BY_ID, {{.MapName}}_BY_NAME };
`

func main() {
	map_name := flag.String("map", "", "")
	type_name := flag.String("type", "", "")
	prefix := flag.String("prefix", "", "")
	flag.Parse()

	file_path := os.Getenv("GOFILE")
	if file_path == "" {
		slog.Error("damn! no file found")
		os.Exit(1)
	}

	generator_data, err := _mappingFromAST(file_path, *type_name)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	if len(generator_data.Items) == 0 {
		slog.Error("damn! no constants found")
		os.Exit(1)
	}

	generator_data.MapName = *map_name
	generator_data.Prefix = *prefix

	tmpl := template.Must(template.New("mapping").Parse(mapping_template))

	var buffer bytes.Buffer
	err = tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	generated_file_path := "../../../shared/mapping_" + strings.ToLower(*map_name) + ".ts"

	file, err := os.Create(generated_file_path)
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, buffer.String())
	slog.Info(generated_file_path + " generated with success!")
}

func _mappingFromAST(file_path string, target_type string) (*generatorMapping, error) {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, file_path, nil, 0)
	if err != nil {
		return nil, err
	}

	var pairs []struct {
		Name string
		ID   uint8
	}
	var current_type_name string
	start_iota := 1

	ast.Inspect(node, func(n ast.Node) bool {
		decl, ok := n.(*ast.GenDecl)
		if !ok || decl.Tok != token.CONST {
			return true
		}

		for _, spec := range decl.Specs {
			vspec, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}

			if vspec.Type != nil {
				if ident, ok := vspec.Type.(*ast.Ident); ok {
					current_type_name = ident.Name
				}
			}

			if current_type_name == target_type {
				for _, id := range vspec.Names {
					if id.Name != "" {
						if strings.HasPrefix(id.Name, "Unknown") {
							continue
						}

						pairs = append(pairs, struct {
							Name string
							ID   uint8
						}{
							Name: id.Name,
							ID:   uint8(start_iota),
						})

						start_iota++
					}
				}
			}
		}
		return true
	})

	return &generatorMapping{
		Items: pairs,
	}, nil
}
