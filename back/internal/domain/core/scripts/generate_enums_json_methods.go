//go:build ignore

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log/slog"
	"os"
	"strings"
	"text/template"
)

type generatorData struct {
	TypeName    string
	TypePrefix  string
	Consts      []string
	UnknownName string
}

const enums_template = `// Code generated by scripts/generate_enums_json_methods. DO NOT EDIT.
package core

import "encoding/json"

func ({{.TypePrefix}} {{.TypeName}}) MarshalJSON() ([]byte, error) {
	return json.Marshal({{.TypePrefix}}.String())
}

func ({{.TypePrefix}} *{{.TypeName}}) UnmarshalJSON(data []byte) error {
	var str string
	err := json.Unmarshal(data, &str)
	if err != nil {
		return err
	}

	switch str {
	{{- range .Consts}}
	case {{.}}.String():
		*{{$.TypePrefix}} = {{.}}
	{{- end}}
	default:
		if len(str) > 0 {
			*{{.TypePrefix}} = {{.UnknownName}}
		}
	}
	return nil
}
`

func main() {
	type_name := flag.String("type", "", "")
	flag.Parse()

	file_path := os.Getenv("GOFILE")
	if file_path == "" {
		slog.Error("damn! no file found")
		os.Exit(1)
	}

	constants, unknown, err := getConstantsFromAST(file_path, *type_name)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	if len(constants) == 0 {
		slog.Error("damn! no constants found")
		os.Exit(1)
	}
	if unknown == "" {
		slog.Error("damn! no Unknown const found")
		os.Exit(1)
	}

	generator_data := generatorData{
		TypeName:    *type_name,
		TypePrefix:  string(strings.ToLower(string(*type_name))[0]),
		Consts:      constants,
		UnknownName: unknown,
	}

	tmpl := template.Must(template.New("enums").Parse(enums_template))

	var buffer bytes.Buffer
	err = tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	generated_file_path := strings.TrimSuffix(file_path, ".go") + "_enums_generated.go"

	file, err := os.Create(generated_file_path)
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, buffer.String())
	slog.Info(generated_file_path + " generated with success!")
}

func getConstantsFromAST(file_path string, target_type string) ([]string, string, error) {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, file_path, nil, 0)
	if err != nil {
		return nil, "", err
	}

	var constants []string
	var unknown string
	var current_type_name string

	ast.Inspect(node, func(n ast.Node) bool {
		decl, ok := n.(*ast.GenDecl)
		if !ok || decl.Tok != token.CONST {
			return true
		}

		for _, spec := range decl.Specs {
			vspec, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}

			if vspec.Type != nil {
				if ident, ok := vspec.Type.(*ast.Ident); ok {
					current_type_name = ident.Name
				}
			}

			if current_type_name == target_type {
				for _, id := range vspec.Names {
					if id.Name != "" {
						if strings.HasPrefix(id.Name, "Unknown") {
							unknown = id.Name
							continue
						}
						constants = append(constants, id.Name)
					}
				}
			}
		}
		return true
	})

	return constants, unknown, nil
}
