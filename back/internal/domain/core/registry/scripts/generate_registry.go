func artifactIsPartOfTransportNetwork(artifact_effects core.Effects) bool {
	if artifact_effects.TravelCost == nil {
		return false
	}

	return slices.ContainsFunc(
		artifact_effects.TravelCost,
		func(effect core.TravelCostEffect) bool {
			switch effect.Type {
			case core.Car, core.Bicycle, core.Bus, core.Subway, core.Train:
				return true
			}

			return false
		},
	)
}
