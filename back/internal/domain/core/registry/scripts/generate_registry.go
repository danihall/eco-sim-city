func main() {
	all_super_kinds := []core.SuperKind{
		data.SeedSuperKindNatural,
		data.SeedSuperKindPublicSystems,
		data.SeedSuperKindIndustrial,
		data.SeedSuperKindResidential,
	}

	generator_data := generatorRegistry{
		Artifacts:                 []core.Artifact{},
		TransportNetworkArtifacts: []core.ArtifactType{},
		Relations:                 []Relation{},
		SuperKinds:                []SuperKindKinds{},
		SocialClasses:             []KindSocialClass{},
		Ordinances:                data.SeedOrdinances,
	}

	for index, super_kind := range all_super_kinds {
		generator_data.SuperKinds = append(generator_data.SuperKinds, SuperKindKinds{
			Name:  super_kind.Name,
			Kinds: []core.KindType{},
		})

		for _, kind := range super_kind.Kinds {
			generator_data.SuperKinds[index].Kinds = append(
				generator_data.SuperKinds[index].Kinds,
				kind.Name,
			)

			if super_kind.Name == core.Residential {
				if kind.SocialClass == nil {
					slog.Error(
						"residential kind does not have a SocialClass attached in its data definition",
						"kind",
						kind.Name,
					)
					os.Exit(1)
				}

				generator_data.SocialClasses = append(generator_data.SocialClasses, KindSocialClass{
					KindName:    kind.Name,
					SocialClass: *kind.SocialClass,
				})
			}

			for _, artifact := range kind.Artifacts {
				artifact.Effects.Spatial = mergeWithSpatialKindEffects(
					artifact.Effects.Spatial,
					kind.Effects.Spatial,
				)
				artifact.Effects.Global = mergeWithGlobalKindEffects(
					artifact.Effects.Global,
					kind.Effects.Global,
				)
				artifact.Effects.TravelCost = mergeWithTravelCostKindEffects(
					artifact.Effects.TravelCost,
					kind.Effects.TravelCost,
				)

				artifact.Requirements.Spatial = mergeWithSpatialKindRequirements(
					artifact.Requirements.Spatial,
					kind.Requirements.Spatial,
				)
				artifact.Requirements.Global = mergeWithGlobalKindRequirements(
					artifact.Requirements.Global,
					kind.Requirements.Global,
				)

				generator_data.Artifacts = append(generator_data.Artifacts, artifact)
				generator_data.Relations = append(generator_data.Relations, Relation{
					Artifact:  artifact.Name,
					SuperKind: super_kind.Name,
					Kind:      kind.Name,
				})

				if artifact.Name != core.ShallowWater && artifact.Name != core.DeepWater &&
					artifact.Effects.TravelCost == nil {
					slog.Error(
						"damn! artifact should be traversable but no TravelCost effect are associated with it",
						"artifact",
						artifact.Name,
					)
					os.Exit(1)
				}

				if (artifact.Width == 0 && artifact.Height != 0) ||
					(artifact.Height == 0 && artifact.Width != 0) {
					slog.Error(
						"damn! a free-size artifact should have both Width and Height set to zero",
						"artifact",
						artifact.Name,
					)
					os.Exit(1)
				}

				if artifactIsPartOfTransportNetwork(artifact.Effects) {
					generator_data.TransportNetworkArtifacts = append(
						generator_data.TransportNetworkArtifacts,
						artifact.Name,
					)
				}
			}
		}
	}

	tmpl := template.Must(template.New("registry").Parse(registry_template))

	var buffer bytes.Buffer
	err := tmpl.Execute(&buffer, generator_data)
	if err != nil {
		slog.Error(err.Error())
		os.Exit(1)
	}

	formatted_code, err := format.Source(buffer.Bytes())
	if err != nil {
		slog.Error("damn!", "cannot format code", err)
		os.Exit(1)
	}

	generated_file_path := "./registry_generated.go"

	file, err := os.Create(generated_file_path)
	if err != nil {
		slog.Error("damn!", "cannot create file", err)
		os.Exit(1)
	}
	defer file.Close()

	fmt.Fprint(file, string(formatted_code))
	slog.Info(generated_file_path + " generated with success!")
}

func mergeWithSpatialKindEffects(
	artifact_effects_spatial []core.SpatialEffect,
	kind_effects_spatial []core.SpatialEffect,
) []core.SpatialEffect {
	merged := make([]core.SpatialEffect, 0, len(artifact_effects_spatial)+len(kind_effects_spatial))
	merged = append(merged, artifact_effects_spatial...)

	for index := range kind_effects_spatial {
		exists := slices.ContainsFunc(artifact_effects_spatial, func(item core.SpatialEffect) bool {
			return kind_effects_spatial[index].Type == item.Type
		})

		if !exists {
			merged = append(merged, kind_effects_spatial[index])
		}
	}

	return merged
}

