type Relation struct {
	Artifact  core.ArtifactType
	SuperKind core.SuperKindType
	Kind      core.KindType
}

type SuperKindKinds struct {
	Name  core.SuperKindType
	Kinds []core.KindType
}

type KindSocialClass struct {
	KindName    core.KindType
	SocialClass core.SocialClass
}

